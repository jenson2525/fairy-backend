package cn.nuaa.jensonxu.fairy.integration.agent.harness.risk;

/**
 * 工具风险等级枚举
 * 用于对 Agent 可调用的工具进行风险分类，驱动 Harness 层的审计粒度、HiL 触发策略和降级行为。
 * 所有接入 Agent 的工具（本地工具、MCP 工具）均需归入其中一个等级。
 */
public enum ToolRiskLevel {

    /**
     * 只读 / 无副作用
     * 工具仅执行查询或计算，不产生任何外部状态变更，失败不影响任何数据。
     * 示例：天气查询、汇率查询、论文搜索、网页抓取、单位换算、时间获取
     */
    READ_ONLY,

    /**
     * 可逆写操作
     * 工具会产生状态变更，但变更可以被撤销或覆盖，风险可控。
     * 示例：保存草稿、创建临时文件、更新日历草稿、写入用户偏好设置
     */
    REVERSIBLE_WRITE,

    /**
     * 不可逆写操作
     * 工具会触发无法自动撤销的外部动作或持久化变更，一旦执行后果难以回退。
     * 示例：发送消息/邮件、提交表单、调用带副作用的第三方 API、删除文件、发布内容
     */
    IRREVERSIBLE_WRITE,

    /**
     * 危险操作
     * 工具执行后可能对用户账户、数据安全或财务造成重大影响，必须经过严格审批。
     * 示例：批量删除数据、账户权限变更、财务操作、清空会话历史
     */
    DANGEROUS
}
